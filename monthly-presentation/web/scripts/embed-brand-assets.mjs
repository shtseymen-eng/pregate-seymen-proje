import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";


const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

async function dataUri(relativePath, mimeType) {
  const bytes = await fs.readFile(path.join(root, relativePath));
  return `data:${mimeType};base64,${bytes.toString("base64")}`;
}

const cover = await dataUri("assets/cover-background.jpg", "image/jpeg");
const content = await dataUri("assets/content-background.jpg", "image/jpeg");
const logo = await dataUri("assets/poliport-logo.png", "image/png");
const source = [
  "// Generated by scripts/embed-brand-assets.mjs. Do not edit by hand.",
  `export const COVER_BACKGROUND_DATA = ${JSON.stringify(cover)};`,
  `export const CONTENT_BACKGROUND_DATA = ${JSON.stringify(content)};`,
  `export const POLIPORT_LOGO_DATA = ${JSON.stringify(logo)};`,
  "",
].join("\n");

await fs.writeFile(path.join(root, "src", "brand-assets.generated.js"), source, "utf8");
